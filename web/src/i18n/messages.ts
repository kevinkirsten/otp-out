export const MESSAGES: Record<Locale, Messages> = { "pt-BR": pt, en, es };

export function detectLocale(languages: readonly string[]): Locale {
  for (const language of languages) {
    const lower = language.toLowerCase();
    if (lower.startsWith("pt")) return "pt-BR";
    if (lower.startsWith("es")) return "es";
    if (lower.startsWith("en")) return "en";
  }
  return "en";
}

export function format(template: string, vars: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
}

export function plural(locale: Locale, forms: Plural, n: number, vars: Record<string, string | number> = {}): string {
  // Zero usa a forma do plural nos três idiomas ("0 contas", "0 accounts", "0 cuentas").
  // O Intl.PluralRules do português põe o 0 na forma "one".
  const rule = n === 0 ? "other" : new Intl.PluralRules(locale).select(n);
  return format(rule === "one" ? forms.one : forms.other, { n, ...vars });
}
